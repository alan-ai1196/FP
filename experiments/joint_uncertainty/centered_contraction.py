"""Stronger latent-world control: center integer excesses before averaging.

For K=2^(n-1) <= 8, the actual s/K is an integer generated by positive
unit syntax. No fraction, latent state, coefficient, or certificate is supplied.
"""
from fractions import Fraction as F
from itertools import product
import argparse
import json

import constraint_contraction as contraction
from fp_reference.program import Sum, Term
from fp_reference.semantics import evaluate
from audit_cuda_primitives import HALF, SINGLE


def centered(n, window):
    assert 2 <= n <= 4
    b = contraction.Builder(n, window)
    worlds = tuple((0,) + z for z in product((0, 1), repeat=n-1))
    K = len(worlds)
    small = b.add((b.one,) * (8 // K))
    pairs = {(lag, i, j): b.mul(b.sources[f'x{lag}:0:{i}'], b.sources[f'x{lag}:1:{j}'])
             for lag in range(window+1) for i, j in product(range(n), repeat=2)}
    labelled = {(lag, i, j, y): b.mul(pairs[lag, i, j], b.sources[f'y{lag}:{y}'])
                for lag in range(1, window+1) for i, j, y in product(range(n), range(n), (0, 1))}
    centered_excesses = []
    query_terms = [[], []]
    for z in worlds:
        excess = b.zero
        for lag in reversed(range(1, window+1)):
            indicator = b.add(labelled[lag, i, j, z[i] ^ z[j]] for i, j in product(range(n), repeat=2))
            # v' = v + I*(8*v + 8/K).  The first eight is an actual slot;
            # the integral 8/K is paid repeated-unit syntax at this initializer.
            scaled = b.emit(Sum('mass', (Term(small, 0), Term(excess, 1))))
            excess = b.add((excess, b.mul(indicator, scaled)))
        centered_excesses.append(excess)
        scaled = b.emit(Sum('mass', (Term(small, 0), Term(excess, 1))))
        for y in (0, 1):
            indicator = b.add(pairs[0, i, j] for i, j in product(range(n), repeat=2) if z[i] ^ z[j] == y)
            query_terms[y].append(b.mul(scaled, indicator))
    common = b.add(centered_excesses)
    return b.finish(b.add((common, b.add(terms))) for terms in query_terms)


def algebra():
    counts = []
    checks = rounded_checks = 0
    maximum_values = set()
    # Exhaust the same n2,H3 domain as the registered comparison; then cover
    # every label pattern of cycles/repeats for the two other admissible K.
    for n in (2, 3, 4):
        rules, graph = centered(n, 3)
        if n == 2:
            histories = tuple(contraction.histories(n, 3))
        else:
            histories = ((),) + tuple(tuple((i, j, y) for (i, j), y in zip(edges, labels))
                for edges in (((0, 1),)*3, ((0, 1), (1, 2), (0, 2)), ((0, 0),)*3)
                for labels in product((0, 1), repeat=3))
        count = 0
        for history in histories:
            for query in product(range(n), repeat=2):
                row = contraction.point(n, 3, history, query)
                values = contraction.integer_values(graph, rules, row)
                expected = contraction.masses(n, history, query)
                assert tuple(1 + values[h] for h in graph.heads) == expected
                maximum_values.update(values)
                if not history or (query == (0, 1) and tuple((i, j) for i, j, y in history) == ((0, 1),)*3):
                    inputs = dict(zip((s.source_id for s in rules.sources), row, strict=True))
                    reference = evaluate(graph, rules, (F(1), F(8)), inputs, (), bit_limit=32768)
                    rounded = contraction.control.model_predict(graph, rules,
                        contraction.control.model_initial(graph, rules, (F(1), F(8))), inputs)
                    assert reference.masses == rounded['masses'] == expected
                    assert tuple(SINGLE.decode(SINGLE.rounded(v/sum(expected))) for v in expected) == rounded['probabilities']
                    rounded_checks += 1
                count += 1
        checks += count
        counts.append({'n': n, 'window': 3, 'graph': graph.counts(), 'forecasts': count,
                       'history_scope': 'all causal histories' if n == 2 else 'empty and all labels on three declared diagnostics'})
    for value in maximum_values:
        assert HALF.decode(HALF.encode_exact(F(value))) == value
    witnesses = {}
    for kind, builder in (('contracted', contraction.contracted), ('enumerated', contraction.enumerated), ('centered', centered)):
        rules, graph = builder(2, 3)
        inputs = dict(zip((s.source_id for s in rules.sources),
                          contraction.point(2, 3, ((0, 1, 0),)*3, (0, 1)), strict=True))
        reference = evaluate(graph, rules, (F(1), F(8)), inputs, (), bit_limit=32768)
        rounded = contraction.control.model_predict(graph, rules,
            contraction.control.model_initial(graph, rules, (F(1), F(8))), inputs)
        witnesses[kind] = {'reference_masses': list(map(str, reference.masses)),
                           'rounded_masses': list(map(str, rounded['masses']))}
    assert witnesses['centered'] == witnesses['contracted'] == {
        'reference_masses': ['3281', '369'], 'rounded_masses': ['3281', '369']}
    assert witnesses['enumerated'] == {'reference_masses': ['6562', '738'], 'rounded_masses': ['6561', '738']}
    assert 'torch' not in contraction.control.sys.modules
    return {'native_forecasts': checks, 'formal_and_rounded_forecasts_each': rounded_checks,
            'distinct_exact_half_node_values': len(maximum_values), 'cases': counts,
            'informative_repeated_edge_witness': witnesses,
            'scope': 'stronger initial model control for integral s/K; no full-state equivalence or owned target authority'}


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--algebra', action='store_true')
    parser.parse_args()
    print(json.dumps(algebra(), indent=2))
